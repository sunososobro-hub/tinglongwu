"""#476: scripts/uninstall.sh removes what the installers created, keeps models unless --purge, and
install.sh / mac_install.sh --uninstall hand over to it. Runs the real scripts in a fake $HOME."""
from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
pytestmark = pytest.mark.skipif(sys.platform == "win32" or not shutil.which("bash"), reason="needs bash")


def _home(tmp_path: Path) -> Path:
    h = tmp_path / "home"
    d = h / "tinglongwu"
    (d / ".git").mkdir(parents=True)
    (d / ".venv").mkdir()
    (d / "pyproject.toml").write_text("")
    (d / "scripts").mkdir()
    shutil.copy(ROOT / "scripts" / "uninstall.sh", d / "scripts" / "uninstall.sh")
    (h / "tts-kokoro").mkdir()
    (h / "models" / "kokoro").mkdir(parents=True)
    (h / "models" / "kokoro" / "x.onnx").write_text("m")
    (h / ".local" / "bin").mkdir(parents=True)
    (h / ".local" / "bin" / "tlwu-menu").write_text("#!/bin/bash\n# generated by mac_install.sh\n")
    (h / ".local" / "bin" / "other-tool").write_text("keep")
    (h / ".zshrc").write_text('alias a=b\nexport PATH="$HOME/.local/bin:$PATH"  # added by tinglongWu\n')
    return h


def _run(cmd: list[str], h: Path) -> subprocess.CompletedProcess:
    env = {k: v for k, v in os.environ.items() if not k.startswith(("TLWU_", "KOKORO_"))}
    env.update(HOME=str(h), TLWU_YES="1")
    return subprocess.run(cmd, env=env, stdin=subprocess.DEVNULL, capture_output=True, text=True, timeout=60)


def test_uninstall_removes_app_keeps_models(tmp_path):
    h = _home(tmp_path)
    r = _run(["bash", str(ROOT / "scripts" / "uninstall.sh")], h)
    assert r.returncode == 0, r.stderr
    assert not (h / "tinglongwu").exists()
    assert not (h / "tts-kokoro").exists()
    assert not (h / ".local" / "bin" / "tlwu-menu").exists()
    assert (h / ".local" / "bin" / "other-tool").exists()
    assert (h / "models" / "kokoro" / "x.onnx").exists()
    assert (h / ".zshrc").read_text() == "alias a=b\n"


def test_purge_removes_models(tmp_path):
    h = _home(tmp_path)
    assert _run(["bash", str(ROOT / "scripts" / "uninstall.sh"), "--purge"], h).returncode == 0
    assert not (h / "models").exists()


def test_refuses_foreign_folder(tmp_path):
    h = _home(tmp_path)
    (h / "tinglongwu" / ".git").rmdir()
    (h / "tinglongwu" / "pyproject.toml").unlink()
    (h / "tinglongwu" / "precious.txt").write_text("x")
    r = _run(["bash", str(ROOT / "scripts" / "uninstall.sh")], h)
    assert r.returncode != 0
    assert (h / "tinglongwu" / "precious.txt").exists()


@pytest.mark.parametrize("script", ["install.sh", "mac_install.sh"])
def test_installers_delegate_uninstall_flag(tmp_path, script):
    h = _home(tmp_path)
    r = _run(["bash", str(ROOT / "scripts" / script), "--uninstall"], h)
    assert r.returncode == 0, r.stderr
    assert "uninstalled" in r.stdout
    assert not (h / "tinglongwu").exists()
