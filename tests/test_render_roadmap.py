"""#661: the roadmap track is rendered from milestones + the latest release, so it never goes stale."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import render_roadmap as rr  # noqa: E402

FOOT = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"


def ms(n, title, o, c, desc="", state="open"):
    return {"number": n, "title": title, "state": state, "open_issues": o, "closed_issues": c,
            "description": desc, "html_url": "https://github.com/o/r/milestone/%d" % n}


MILESTONES = [ms(2, "v0.4", 12, 42, "beginner edition" + FOOT), ms(3, "Later", 15, 7, "frozen"),
              ms(4, "mobile 0.2", 7, 1, "phone track"), ms(6, "v0.5", 11, 9, "faster"),
              ms(8, "v0.3.5", 7, 15, "slim zip" + FOOT), ms(5, "v0.3.3", 0, 5, "mac fix", state="closed")]


def fake_api(releases_tag="v0.3.4", milestones=MILESTONES):
    calls = []

    def api(path):
        calls.append(path)
        if path.endswith("/releases/latest"):
            return {"tag_name": releases_tag}
        if "/milestones" in path:
            return [m for m in milestones if m["state"] == "open"] if "page=1" in path else []
        raise AssertionError(path)
    return api, calls


def test_plan_here_next_and_order():
    p = rr.plan("v0.3.4", MILESTONES)
    assert p["here"] == "v0.3.4"
    assert [c["title"] for c in p["columns"]] == ["v0.3.5", "v0.4", "v0.5", "mobile 0.2", "Later"]
    assert [c["role"] for c in p["columns"]] == ["next", "later", "later", "later", "later"]
    assert p["columns"][0]["theme"] == "slim zip"  # agent footer stripped
    assert (p["columns"][0]["open"], p["columns"][0]["closed"]) == (7, 15)


def test_next_moves_by_itself_when_a_milestone_closes():
    closed = [dict(m, state="closed") if m["title"] == "v0.3.5" else m for m in MILESTONES]
    p = rr.plan("v0.3.5", closed)
    assert p["here"] == "v0.3.5" and p["columns"][0]["title"] == "v0.4" and p["columns"][0]["role"] == "next"


def test_main_renders_track_and_replaces_stale_next_card(tmp_path):
    out = tmp_path / "roadmap.html"
    api, _ = fake_api()
    assert rr.main([str(ROOT / "docs" / "roadmap.html"), str(out), "--repo", "o/r"], api=api) == 0
    page = out.read_text("utf-8")
    track = page[page.index(rr.T_START):page.index(rr.T_END)]
    assert track.count('class="tc ') == 6  # you are here + 5 open milestones
    assert "<h3>v0.3.4</h3>" in track and 'class="tc next"' in track
    assert track.index(">v0.3.5<") < track.index(">v0.4<") < track.index(">v0.5<") < track.index(">Later<")
    assert "15 / 22" in track and "42 / 54" in track  # closed / total per milestone
    assert "Generated by" not in track
    card = page[page.index(rr.N_START):page.index(rr.N_END)]
    assert "<b>v0.3.5</b>" in card and "milestone/8" in card  # support.json said v0.3.2: replaced


def test_main_keeps_next_card_when_it_matches(tmp_path):
    src = (ROOT / "docs" / "roadmap.html").read_text("utf-8")
    nxt = json.loads((ROOT / "docs" / "support.json").read_text("utf-8"))["next_release"]["version"]
    mss = [ms(9, nxt, 1, 1, "x")]
    api, _ = fake_api(milestones=mss)
    out = tmp_path / "r.html"
    rr.main([str(ROOT / "docs" / "roadmap.html"), str(out), "--repo", "o/r"], api=api)
    page = out.read_text("utf-8")
    card = lambda s: s[s.index(rr.N_START):s.index(rr.N_END)]
    assert card(page) == card(src)


def test_main_api_down_copies_page_unchanged(tmp_path):
    def api(path):
        raise OSError("network down")
    out = tmp_path / "r.html"
    assert rr.main([str(ROOT / "docs" / "roadmap.html"), str(out), "--repo", "o/r"], api=api) == 0
    assert out.read_text("utf-8") == (ROOT / "docs" / "roadmap.html").read_text("utf-8")


def test_static_page_has_one_track_block():
    page = (ROOT / "docs" / "roadmap.html").read_text("utf-8")
    assert page.count(rr.T_START) == 1 and page.count(rr.T_END) == 1


def test_track_shows_progress_rings_with_percent_and_empty_milestone():
    track = rr.render_track(rr.plan("v0.3.4", MILESTONES))
    assert 'class="track timeline"' in track
    assert track.count('class="ring"') == 5  # one ring per open milestone, none for "you are here"
    assert 'stroke-dasharray="68 32"' in track and ">68%</text>" in track  # v0.3.5: 15/22
    assert 'stroke-dasharray="78 22"' in track  # v0.4: 42/54
    assert 'class="bar"' not in track
    empty = rr.render_track(rr.plan(None, [ms(9, "v1", 0, 0)]))
    assert 'stroke-dasharray="0 100"' in empty and ">0%</text>" in empty  # no issues: empty ring, no crash
