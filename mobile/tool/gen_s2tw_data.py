"""Generate mobile/lib/logic/s2tw_data.dart from the OpenCC dictionaries (Apache-2.0).

The dictionaries are read from the `opencc-python-reimplemented` package that desktop already pins
(requirements.txt), so the phone converts with the same data as desktop `translate.zh_convert(..., "tw")`
(OpenCC s2twp). Run from the repo root after `pip install -r requirements.txt`:

    python mobile/tool/gen_s2tw_data.py

Tables written (all derived, nothing hand-edited):
- chars: STCharacters, first candidate per character (what OpenCC picks when no phrase matches).
- phrases: STPhrases entries whose target differs from the char-by-char result (the rest are redundant).
- twPhrases: TWPhrases (Taiwan wording: 软件 -> 軟體 ...), applied to the Traditional text.
- twVariants: TWVariants (Taiwan glyph variants: 裏 -> 裡 ...), applied last.
"""

import os
import sys

import opencc

OUT = os.path.join(os.path.dirname(__file__), "..", "lib", "logic", "s2tw_data.dart")
DICT = os.path.join(os.path.dirname(opencc.__file__), "dictionary")
WIDTH = 240  # characters per string line in the generated file


def load(name: str) -> dict[str, str]:
    table = {}
    with open(os.path.join(DICT, name), encoding="utf-8") as f:
        for line in f:
            key, values = line.rstrip("\n").split("\t")
            table[key] = values.split(" ")[0]
    return table


def pairs(table: dict[str, str]) -> str:
    """'key=value key=value ...' (keys and values never contain '=' or ' ')."""
    return " ".join(f"{k}={v}" for k, v in sorted(table.items()))


def dart_const(name: str, text: str) -> str:
    lines = [text[i : i + WIDTH] for i in range(0, len(text), WIDTH)] or [""]
    body = "\n".join(f"    '{line}'" for line in lines)
    return f"const String {name} =\n{body};\n"


def main() -> int:
    chars = {k: v for k, v in load("STCharacters.txt").items() if k != v}
    by_char = lambda s: "".join(chars.get(c, c) for c in s)  # noqa: E731
    phrases = {k: v for k, v in load("STPhrases.txt").items() if by_char(k) != v}
    tw_phrases = load("TWPhrases.txt")
    tw_variants = {k: v for k, v in load("TWVariants.txt").items() if k != v}
    for table in (chars, phrases, tw_phrases, tw_variants):
        assert not any(set(k + v) & set("= '$\\\n") for k, v in table.items())  # safe in a Dart '...' literal
    src = sorted(chars)
    out = [
        "// GENERATED by mobile/tool/gen_s2tw_data.py from the OpenCC dictionaries; do not edit by hand.",
        "// OpenCC data: Copyright BYVoid and contributors, Apache License 2.0 (https://github.com/BYVoid/OpenCC).",
        f"// chars={len(chars)} phrases={len(phrases)} twPhrases={len(tw_phrases)} twVariants={len(tw_variants)}",
        "",
        "/// Simplified characters; [s2twTargets] holds the Traditional form at the same rune index.",
        dart_const("s2twSources", "".join(src)),
        "/// Traditional forms for [s2twSources] (OpenCC STCharacters, first candidate).",
        dart_const("s2twTargets", "".join(chars[c] for c in src)),
        "/// OpenCC STPhrases entries that differ from the char-by-char result ('simp=trad', space separated).",
        dart_const("s2twPhrases", pairs(phrases)),
        "/// OpenCC TWPhrases: Taiwan wording on Traditional text ('trad=taiwan').",
        dart_const("s2twTwPhrases", pairs(tw_phrases)),
        "/// OpenCC TWVariants: Taiwan glyph variants ('trad=taiwan').",
        dart_const("s2twTwVariants", pairs(tw_variants)),
    ]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print(f"wrote {os.path.normpath(OUT)}: chars={len(chars)} phrases={len(phrases)}"
          f" twPhrases={len(tw_phrases)} twVariants={len(tw_variants)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
