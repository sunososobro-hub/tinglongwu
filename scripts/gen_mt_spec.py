"""Generate the files derived from shared/mt_spec.json (#1895, parent #1816).

    python scripts/gen_mt_spec.py          # rewrite the derived files
    python scripts/gen_mt_spec.py --check  # exit 1 when a derived file is out of date

Derived: mobile/lib/logic/mt_spec.g.dart (the phone's tables and templates) and
src/core/tinglongwu/data/mt_spec.json (byte copy bundled with the desktop package, which has no `shared/` folder).
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "shared" / "mt_spec.json"
DESKTOP_COPY = ROOT / "src" / "core" / "tinglongwu" / "data" / "mt_spec.json"
DART = ROOT / "mobile" / "lib" / "logic" / "mt_spec.g.dart"


def _q(s: str) -> str:
    """Dart single-quoted literal; the spec text holds no quote, backslash or `$` other than placeholders."""
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$").replace("\n", "\\n") + "'"


def render_dart(spec: dict) -> str:
    phone = [x for x in spec["languages"] if x["phone"]]
    t = spec["templates"]
    out = ["// GENERATED by scripts/gen_mt_spec.py from shared/mt_spec.json (#1895). Do not edit.",
           "// ignore_for_file: lines_longer_than_80_chars",
           "library;", "", "class MtSpec {",
           "  static const zhNames = <String, String>{"]
    out += [f"    {_q(x['code'])}: {_q(x['zh'])}," for x in phone]
    out += ["  };", "  static const enNames = <String, String>{"]
    out += [f"    {_q(x['code'])}: {_q(x['en'])}," for x in phone]
    out += ["  };",
            "  /// Languages whose presence on either side selects the Chinese card (desktop rule).",
            "  static const chineseSide = <String>[" + ", ".join(_q(c) for c in spec["chinese_side"]) + "];"]
    for key in ("zh", "en", "context", "terms", "term_line"):
        name = "".join(p.capitalize() if i else p for i, p in enumerate(key.split("_")))
        out.append(f"  static const {name}Template = {_q(t[key])};")
    out += ["}", ""]
    return "\n".join(out)


def main() -> int:
    raw = SPEC.read_text(encoding="utf-8")
    want = {DESKTOP_COPY: raw, DART: render_dart(json.loads(raw))}
    if "--check" in sys.argv:
        bad = [str(p) for p, text in want.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        for b in bad:
            print(f"out of date: {b} (run python scripts/gen_mt_spec.py)")
        return 1 if bad else 0
    for p, text in want.items():
        p.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
