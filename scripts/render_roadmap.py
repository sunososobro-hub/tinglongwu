"""Render the roadmap track of docs/roadmap.html from GitHub milestones + the latest release (#661).

The page never goes stale: "you are here" = the latest published release tag, "next" = the open milestone with
the lowest version, then the other open milestones (versions in order, then other tracks such as "mobile 0.2",
"Later" last). Each column shows the milestone title, its description as the theme text (owner 2026-11-14:
milestones are the single source) and its open / closed issue counts.

  python scripts/render_roadmap.py docs/roadmap.html site/roadmap.html --repo owner/name

Run by the stats-dashboard workflow. Fills the block between <!-- ROADMAP-TRACK:START --> and
<!-- ROADMAP-TRACK:END -->. When support.json's "Next release" card names another version than the computed next
milestone, the card (<!-- ROADMAP-NEXT:... -->) is replaced by one built from that milestone. If the API cannot be
read, the page is copied unchanged (its static fallback links to the milestones list) and the script exits 0.
"""
import argparse
import html
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from stats_dashboard import _pages, http_api  # noqa: E402

T_START, T_END = "<!-- ROADMAP-TRACK:START -->", "<!-- ROADMAP-TRACK:END -->"
N_START, N_END = "<!-- ROADMAP-NEXT:START -->", "<!-- ROADMAP-NEXT:END -->"
_VER = re.compile(r"^v(\d+(?:\.\d+)*)$")
FOOTER = re.compile(r"\n\s*---\s*\n.*", re.S)  # agent footer under the description ("---\n_Generated by ..._")


def version_key(title):
    """'v0.3.5' -> (0, 3, 5); not a plain version -> None."""
    m = _VER.match((title or "").strip())
    return tuple(int(x) for x in m.group(1).split(".")) if m else None


def theme_text(desc):
    return FOOTER.sub("", desc or "").strip()


def plan(latest_tag, milestones):
    """-> {'here': tag or None, 'columns': [{'role': 'next'|'later', 'title', 'theme', 'open', 'closed', 'url'}]}.

    Only open milestones are columns. next = the open milestone with the lowest version; then the other versions
    in order, then other open milestones by title, a milestone titled 'Later' last.
    """
    opened = [m for m in milestones if m.get("state", "open") == "open"]
    vers = sorted((m for m in opened if version_key(m["title"])), key=lambda m: version_key(m["title"]))
    rest = sorted((m for m in opened if not version_key(m["title"])),
                  key=lambda m: (m["title"].strip().lower() == "later", m["title"].lower()))
    cols = []
    for i, m in enumerate(vers + rest):
        cols.append({"role": "next" if (i == 0 and vers) else "later", "title": m["title"],
                     "theme": theme_text(m.get("description")), "open": m.get("open_issues", 0),
                     "closed": m.get("closed_issues", 0), "url": m.get("html_url", "")})
    return {"here": latest_tag, "columns": cols}


def _lab(zh_tw, en, zh_cn, cls, tag="span"):
    e = lambda s: html.escape(s, quote=True)
    return f'<{tag} class="{cls}" data-en="{e(en)}" data-zh-cn="{e(zh_cn)}">{html.escape(zh_tw)}</{tag}>'


def render_track(p):
    """Track block (markers included): one card for "you are here", one per open milestone."""
    out = [T_START, '<div class="track">']
    if p["here"]:
        out += ['  <section class="tc here">', "    " + _lab("你在這裡", "You are here", "你在这里", "role"),
                f'    <h3>{html.escape(p["here"])}</h3>',
                "    " + _lab("最新發佈版", "Latest published release", "最新发布版", "cnt", "p"), "  </section>"]
    for c in p["columns"]:
        role = (("下一版", "Next release", "下一版") if c["role"] == "next" else ("之後", "Later", "之后"))
        total = c["open"] + c["closed"]
        pct = round(100 * c["closed"] / total) if total else 0
        out += [f'  <section class="tc {c["role"]}">', "    " + _lab(*role, "role"),
                f'    <h3><a href="{html.escape(c["url"], quote=True)}">{html.escape(c["title"])}</a></h3>',
                f'    <p class="theme">{html.escape(c["theme"])}</p>' if c["theme"] else "",
                f'    <div class="bar" role="img" aria-label="{c["closed"]}/{total}"><i style="width:{pct}%"></i></div>',
                f'    <p class="cnt">{c["closed"]} / {total} '
                + _lab("張完成", "issues done", "张完成", "u") + "</p>", "  </section>"]
    out += ["</div>", T_END]
    return "\n".join(x for x in out if x)


def render_next(col):
    """'Next release' card built from the next milestone (used when support.json's card names another version)."""
    t = html.escape(col["title"])
    return "\n".join(x for x in [
        N_START, '<section class="next" aria-label="Next release">',
        f'  <div class="nt">{_lab("下一版", "Next release", "下一版", "tag")} <b>{t}</b></div>',
        f'  <p class="dt">{html.escape(col["theme"])}</p>' if col["theme"] else "",
        f'  <a class="go" href="{html.escape(col["url"], quote=True)}" data-en="See everything planned for {t}"'
        f' data-zh-cn="看 {t} 的完整清单">看 {t} 的完整清單</a>',
        "</section>", N_END] if x)


def _replace(page, start, end, block):
    i, j = page.find(start), page.find(end)
    if i < 0 or j < i:
        raise ValueError(f"expected one {start} ... {end} block")
    return page[:i] + block + page[j + len(end):]


def render_page(page, p):
    page = _replace(page, T_START, T_END, render_track(p))
    nxt = next((c for c in p["columns"] if c["role"] == "next"), None)
    m = re.search(re.escape(N_START) + r".*?<b>([^<]*)</b>", page, re.S)
    if nxt and (not m or m.group(1).strip() != nxt["title"]):
        page = _replace(page, N_START, N_END, render_next(nxt))
    return page


def fetch(api, repo):
    try:
        tag = api("/repos/%s/releases/latest" % repo).get("tag_name")
    except Exception as e:  # no release yet: no "you are here" card
        print("latest release unavailable: %s" % e, file=sys.stderr)
        tag = None
    return tag, _pages(api, "/repos/%s/milestones?state=open" % repo)


def main(argv=None, api=http_api):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("src")
    ap.add_argument("out")
    ap.add_argument("--repo", required=True)
    a = ap.parse_args(argv)
    with open(a.src, encoding="utf-8") as f:
        page = f.read()
    try:
        page = render_page(page, plan(*fetch(api, a.repo)))
    except Exception as e:  # keep the static page (fallback links to the milestones list)
        print("roadmap track not rendered: %s" % e, file=sys.stderr)
    with open(a.out, "w", encoding="utf-8") as f:
        f.write(page)
    return 0


if __name__ == "__main__":
    sys.exit(main())
